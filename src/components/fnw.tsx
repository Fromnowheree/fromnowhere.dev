export function ButtonLink({
  href,
  variant = 'secondary',
  icon,
  iconRight,
  iconOnly,
  children,
}: {
  href: string
  variant?: 'primary' | 'secondary' | 'ghost'
  icon?: IconName
  iconRight?: IconName
  /** Square button showing only the icon; children (a string) become its label. */
  iconOnly?: boolean
  children: React.ReactNode
}) {
  const className = cx('fnw-btn', `fnw-btn--${variant}`, iconOnly && 'fnw-btn--icon')
  const label = iconOnly && typeof children === 'string' ? children : undefined
  const content = iconOnly ? (
    icon && <Icon name={icon} size={18} />
  ) : (
    <>
      {icon && <Icon name={icon} size={16} />}
      {children}
      {iconRight && <Icon name={iconRight} size={16} />}
    </>
  )
  // Links within the site navigate client-side, so the page can crossfade (design/motion.md).
  return isInternal(href) ? (
    <Link className={className} href={href} aria-label={label}>
      {content}
    </Link>
  ) : (
    <a className={className} href={href} aria-label={label}>
      {content}
    </a>
  )
}

