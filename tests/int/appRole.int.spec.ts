import { readFileSync } from 'node:fs'

import pg from 'pg'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'

/**
 * The app's own database login (db/init/app-role.psql), run against the real test Postgres in a
 * database of its own. The property: the app can do everything a migration does to the site's
 * database, including to what an install from before 0.1.4 made as the superuser, and nothing a
 * superuser could (run a program, make a role or a database).
 *
 * The script is psql's; its two variables (`:'pw'`, `:"db"`) are filled in here the way psql
 * fills them in, quoted as a literal and as a name.
 */
const base = process.env.DATABASE_URL
if (!base) throw new Error('DATABASE_URL is not set')

const name = `pw_test_app_role_${process.pid}_${Date.now()}`
const password = 'app-role-test-password'
const urlOf = (database: string, user?: { name: string; password: string }) => {
  const url = new URL(base)
  url.pathname = `/${database}`
  if (user) {
    url.username = user.name
    url.password = user.password
  }
  return url.toString()
}

const connect = async (url: string) => {
  const client = new pg.Client({ connectionString: url })
  await client.connect()
  return client
}

let superuser: pg.Client
let app: pg.Client

const runScript = async () => {
  const script = readFileSync('db/init/app-role.psql', 'utf8')
    .replace(":'pw'", superuser.escapeLiteral(password))
    .replace(':"db"', superuser.escapeIdentifier(name))
  await superuser.query(script)
}

/** Everything in the site's schema that `app` does not own: tables, sequences, views, types. */
const notOwned = async () =>
  (
    await superuser.query(`
      SELECT c.relname AS name FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = 'public' AND pg_get_userbyid(c.relowner) <> 'app'
      UNION ALL
      SELECT t.typname FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
      WHERE n.nspname = 'public' AND t.typtype IN ('e', 'd') AND pg_get_userbyid(t.typowner) <> 'app'`)
  ).rows.map((row) => row.name)

beforeAll(async () => {
  const maintenance = await connect(base)
  await maintenance.query(`CREATE DATABASE "${name}"`)
  await maintenance.end()
  superuser = await connect(urlOf(name))
  // An install from before 0.1.4: what the migrations make (enums, tables with serial and
  // identity columns, indexes, a foreign key, a sequence of its own), made by the superuser.
  await superuser.query(`
    CREATE TYPE enum_pages_status AS ENUM ('draft', 'published');
    CREATE TABLE pages (id serial PRIMARY KEY, status enum_pages_status, title varchar);
    CREATE TABLE pages_blocks (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      parent_id integer REFERENCES pages (id) ON DELETE CASCADE
    );
    CREATE INDEX pages_blocks_parent_idx ON pages_blocks (parent_id);
    CREATE SEQUENCE loose_counter;
    CREATE VIEW published_pages AS SELECT id FROM pages WHERE status = 'published';
    INSERT INTO pages (status, title) VALUES ('published', 'Home');
  `)
  await runScript()
  app = await connect(urlOf(name, { name: 'app', password }))
})

afterAll(async () => {
  await app?.end()
  await superuser?.end()
  const maintenance = await connect(base)
  await maintenance.query(`DROP DATABASE IF EXISTS "${name}" WITH (FORCE)`)
  await maintenance.query('DROP ROLE IF EXISTS app')
  await maintenance.end()
})

describe("the app's database login", () => {
  it('owns everything an earlier install made as the superuser', async () => {
    expect(await notOwned()).toEqual([])
  })

  it('can make every change a migration makes to it', async () => {
    await app.query(`ALTER TYPE enum_pages_status ADD VALUE 'archived'`)
    await app.query('ALTER TABLE pages ADD COLUMN slug varchar')
    await app.query('CREATE INDEX pages_slug_idx ON pages (slug)')
    await app.query('ALTER TABLE pages_blocks ADD COLUMN position integer')
    await app.query('ALTER TABLE pages_blocks DROP CONSTRAINT pages_blocks_parent_id_fkey')
    await app.query(`INSERT INTO pages (status, title) VALUES ('draft', 'About')`)
    await app.query(`SELECT nextval('loose_counter')`)
    await app.query('DROP VIEW published_pages')
    await app.query(`CREATE TYPE enum_new AS ENUM ('a'); CREATE TABLE new_table (id serial)`)
    await app.query('DROP TABLE new_table; DROP TYPE enum_new')
  })

  it('is no superuser: no programs, no roles, no databases', async () => {
    const { rows } = await app.query(`SELECT rolsuper FROM pg_roles WHERE rolname = 'app'`)
    expect(rows[0].rolsuper).toBe(false)
    await expect(app.query(`COPY (SELECT 1) TO PROGRAM 'true'`)).rejects.toThrow(/permission/i)
    await expect(app.query(`CREATE ROLE intruder`)).rejects.toThrow(/permission/i)
    await expect(app.query(`CREATE DATABASE intruder`)).rejects.toThrow(/permission/i)
  })

  it('can be set up again on the same database, changing nothing', async () => {
    await runScript()
    expect(await notOwned()).toEqual([])
    const { rows } = await app.query('SELECT count(*)::int AS pages FROM pages')
    expect(rows[0].pages).toBe(2)
  })
})
